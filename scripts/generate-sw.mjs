import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const { loadEnvConfig } = require("@next/env");

const root = process.cwd();
const isDev = process.argv.includes("--dev");
const checkOnly = process.argv.includes("--check");

loadEnvConfig(root, isDev);

const templatePath = path.resolve(root, "scripts/sw-template.js");
const template = fs.readFileSync(templatePath, "utf8");

const sourceDirectories = ["app", "context", "lib", "utils", "public"];
const sourceFiles = [
  "proxy.js",
  "next.config.mjs",
  "package-lock.json",
  "package.json",
  "scripts/sw-template.js",
  "public/sw-policies.js",
];

function walk(directory) {
  if (!fs.existsSync(directory)) return [];
  return fs.readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const fullPath = path.join(directory, entry.name);
    if (entry.isDirectory()) return walk(fullPath);
    if (entry.isFile()) return [fullPath];
    return [];
  });
}

function isHashedSource(file) {
  const relative = path.relative(root, file).replaceAll("\\", "/");
  if (relative === "public/sw.js") return false;
  if (/\.(map|log)$/i.test(relative)) return false;
  if (/(^|\/)(\.DS_Store|Thumbs\.db)$/i.test(relative)) return false;
  return true;
}

const hash = crypto.createHash("sha256");
hash.update("sw-template:").update(template);

const files = sourceDirectories
  .flatMap((directory) => walk(path.resolve(root, directory)))
  .concat(sourceFiles.map((file) => path.resolve(root, file)))
  .filter((file) => fs.existsSync(file) && isHashedSource(file))
  .sort((a, b) => a.localeCompare(b));

for (const file of files) {
  hash.update(path.relative(root, file).replaceAll("\\", "/"));
  hash.update("\0");
  hash.update(fs.readFileSync(file));
  hash.update("\0");
}

const sourceHash = hash.digest("hex");
const version = String(process.env.PWA_CACHE_VERSION || sourceHash.slice(0, 12));

function toOrigin(value) {
  if (!value) return null;
  try {
    const url = new URL(value);
    if (url.protocol !== "http:" && url.protocol !== "https:") return null;
    return url.origin;
  } catch {
    return null;
  }
}

const apiOrigins = Array.from(
  new Set(
    [
      toOrigin(process.env.NEXT_PUBLIC_API_BASE_URL),
      toOrigin(process.env.API_BASE_URL),
      toOrigin(process.env.NEXT_PUBLIC_API_IMAGE_BASE_URL),
    ].filter(Boolean),
  ),
);

const localApiOrigins = apiOrigins.filter((origin) => {
  try {
    const hostname = new URL(origin).hostname.toLowerCase();
    return (
      hostname === "localhost" ||
      hostname === "127.0.0.1" ||
      hostname === "0.0.0.0" ||
      hostname === "::1" ||
      hostname === "[::1]"
    );
  } catch {
    return false;
  }
});

if (
  !isDev &&
  localApiOrigins.length > 0 &&
  process.env.PWA_ALLOW_LOCAL_ORIGINS !== "true"
) {
  console.error(
    [
      "Refusing to generate a production service worker with local API origins:",
      ...localApiOrigins.map((origin) => `  - ${origin}`),
      "Set PWA_ALLOW_LOCAL_ORIGINS=true only for local/e2e builds.",
    ].join("\n"),
  );
  process.exit(1);
}

const precacheUrls = [
  "/offline.html",
  "/manifest.webmanifest",
  "/favicon.ico",
  "/icons/icon-192.png",
  "/icons/icon-512.png",
  "/icons/icon-192-maskable.png",
  "/icons/icon-512-maskable.png",
  "/icons/apple-touch-icon.png",
  "/Images/logo.png",
];

const generated = [
  `// Generated by scripts/generate-sw.mjs — cache version ${version}`,
  template
    .replace("__SW_VERSION__", JSON.stringify(version))
    .replace("__PRECACHE_URLS__", JSON.stringify(precacheUrls, null, 2))
    .replace("__API_ORIGINS__", JSON.stringify(apiOrigins, null, 2))
    .replace("__IS_DEV__", isDev ? "true" : "false"),
].join("\n");

const outputPath = path.resolve(root, "public/sw.js");
const current = fs.existsSync(outputPath)
  ? fs.readFileSync(outputPath, "utf8")
  : null;

if (checkOnly) {
  if (current !== generated) {
    console.error("public/sw.js is out of date. Run npm run pwa:generate.");
    process.exit(1);
  }
  console.log(`Service worker is up to date (${version}).`);
  process.exit(0);
}

if (current !== generated) {
  fs.writeFileSync(outputPath, generated);
  console.log(
    `Generated public/sw.js (version ${version}, ${precacheUrls.length} precached URLs).`,
  );
} else {
  console.log(`public/sw.js is already current (version ${version}).`);
}
